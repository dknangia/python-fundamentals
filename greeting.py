name = 'Deepak\'s ball' # notice that we used another '\ to escape the single quote in the string.
print("Hello, " + name) # notice we used + to concatenate the string. We can also use , to concatenate the string, but it will add a space between the strings.
print("Hello", name) # using , to concatenate the string, it will add a space between the strings.

